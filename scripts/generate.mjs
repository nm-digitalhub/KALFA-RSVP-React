import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import { toString } from 'mdast-util-to-string';
import * as heModule from 'he';
const he = heModule.default ?? heModule;

const clean = value => he.decode(value).replace(/<br\s*\/?\s*>/gi, '\n').trim();
const text = node => clean(toString(node));
const links = node => {
  const result = [];
  function walk(n) {
    if (n.type === 'link') result.push({ text: text(n), url: n.url });
    for (const child of n.children ?? []) walk(child);
  }
  walk(node);
  return result;
};

export function extract(markdown) {
  const tree = unified().use(remarkParse).use(remarkGfm).parse(markdown);
  const headings = [];
  const entries = [];
  let sourceRows = 0;
  for (const node of tree.children) {
    if (node.type === 'heading') {
      headings.length = node.depth - 1;
      headings[node.depth - 1] = text(node);
      continue;
    }
    if (node.type !== 'table') continue;
    const [header, ...rows] = node.children;
    const columns = header.children.map(text);
    if (columns[0] === 'Property') continue;
    if (!['Code', 'Error'].includes(columns[0])) throw new Error(`Unknown table at line ${node.position.start.line}`);
    const marketing = headings.includes('Marketing Messages API for WhatsApp error codes');
    const expected = marketing
      ? ['Code', 'Message', 'Details', 'Possible reasons and solutions', 'HTTP status code']
      : columns[0] === 'Code'
        ? ['Code', 'details', 'Possible reasons and solutions']
        : ['Error', 'Description', 'Possible solution'];
    if (columns.map(c => c.replace(/\s+/g, ' ').toLowerCase()).join('|') !== expected.map(c => c.toLowerCase()).join('|')) {
      throw new Error(`Unexpected columns at line ${node.position.start.line}`);
    }
    for (const row of rows) {
      if (row.children.length !== expected.length) throw new Error(`Unexpected cells at line ${row.position.start.line}`);
      sourceRows++;
      const cells = row.children.map(text);
      const first = cells[0];
      const range = /^(\d+)-(\d+)$/.exec(first);
      const prefix = /^(\d+(?:\s*,\s*\d+)*)(?=$|\s|<)/.exec(first);
      if (!range && !prefix) throw new Error(`Unrecognized code at line ${row.position.start.line}: ${first}`);
      const codes = range ? [null] : prefix[1].split(',').map(v => Number(v.trim()));
      const title = range ? null : first.slice(prefix[1].length).replace(/^\s*-\s*/, '').trim() || null;
      for (const code of codes) entries.push({
        api: marketing ? 'marketing' : 'cloud',
        section: headings.filter(Boolean).slice(1).join(' / '),
        sourceLine: row.position.start.line,
        kind: range ? 'range' : 'exact',
        code,
        min: range ? Number(range[1]) : null,
        max: range ? Number(range[2]) : null,
        title: marketing ? null : title,
        message: marketing ? cells[1] : null,
        description: marketing ? cells[2] : cells[1],
        solution: marketing ? cells[3] : cells[2],
        httpStatus: marketing ? Number(cells[4].match(/^\d{3}/)?.[0]) : null,
        httpStatusText: marketing ? cells[4] : null,
        links: links(row),
      });
    }
  }
  if (!sourceRows) throw new Error('No error rows found');
  const knownCodes = [...new Set(entries.filter(e => e.kind === 'exact').map(e => e.code))].sort((a,b) => a-b);
  return { entries, knownCodes, sourceRows };
}

export function render(markdown) {
  const { entries, knownCodes, sourceRows } = extract(markdown);
  const hash = createHash('sha256').update(markdown).digest('hex');
  return `// Generated by scripts/generate.mjs. Do not edit.\n// Source SHA256: ${hash}\n// Source rows: ${sourceRows}; entries: ${entries.length}; exact codes: ${knownCodes.length}.\n
export interface WhatsAppErrorDefinition {
  readonly api: 'cloud' | 'marketing';
  readonly section: string;
  readonly sourceLine: number;
  readonly kind: 'exact' | 'range';
  readonly code: number | null;
  readonly min: number | null;
  readonly max: number | null;
  readonly title: string | null;
  readonly message: string | null;
  readonly description: string;
  readonly solution: string;
  readonly httpStatus: number | null;
  readonly httpStatusText: string | null;
  readonly links: readonly { readonly text: string; readonly url: string }[];
}

export const whatsappErrorCodes = ${JSON.stringify(knownCodes)} as const;
export type WhatsAppKnownErrorCode = typeof whatsappErrorCodes[number];
export const whatsappErrors: readonly WhatsAppErrorDefinition[] = ${JSON.stringify(entries, null, 2)};

export function isKnownWhatsAppErrorCode(code: number): code is WhatsAppKnownErrorCode {
  return (whatsappErrorCodes as readonly number[]).includes(code);
}

export function lookupWhatsAppErrors(code: number, api: 'cloud' | 'marketing' = 'cloud'): readonly WhatsAppErrorDefinition[] {
  if (!Number.isSafeInteger(code) || code < 0) return [];
  const applicable = whatsappErrors.filter(e => e.api === 'cloud' || api === 'marketing');
  const exact = applicable.filter(e => e.kind === 'exact' && e.code === code);
  if (exact.length) return exact;
  return applicable.filter(e => e.kind === 'range' && e.min !== null && e.max !== null && code >= e.min && code <= e.max);
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    const check = args.includes('--check');
    const positional = args.filter(a => a !== '--check');
    if (positional.length > 2) throw new Error('Usage: node scripts/generate.mjs [input.md] [output.ts] [--check]');
    const input = positional[0] ?? 'docs/error-codes.md';
    const output = positional[1] ?? 'src/whatsapp-error-codes.ts';
    const markdown = await readFile(input, 'utf8');
    const generated = render(markdown);
    if (check) {
      if (await readFile(output, 'utf8') !== generated) throw new Error('Generated file is stale. Run npm run generate.');
      console.log('[OK] Generated file is current.');
    } else {
      await mkdir(dirname(resolve(output)), { recursive: true });
      await writeFile(output, generated);
      const data = extract(markdown);
      console.log(`[OK] ${data.sourceRows} source rows; ${data.entries.length} entries; ${data.knownCodes.length} exact codes.`);
    }
  } catch (error) {
    console.error('[X]', error.message);
    process.exitCode = 1;
  }
}
