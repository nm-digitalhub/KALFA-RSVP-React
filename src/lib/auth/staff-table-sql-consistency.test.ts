import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

import {
  STAFF_TABLE_PERMISSIONS,
  staffTableOperationKeys,
  type StaffTable,
  type TableOperation,
} from './staff-table-permissions';
import { policyName } from './staff-table-rls';

// staff-tables-permission-rls, design D10, task 5.1: the key each per-operation policy names in the SQL equals the key
// the map gives that operation. The map takes a CASL table's keys from PLATFORM_ACTIONS (packages), so a change made
// there alone moves the map with it, and only the SQL is an independent side: this test reads the migrations and the
// generated pgTAP files as text and fails naming the table and the operation.
//
// It covers every per-permission table whose `<table>_<op>_permission` policies a migration has created (its stage
// has landed); a table whose stage has not landed yet has none and is skipped.

const ROOT = join(__dirname, '..', '..', '..');
const OPS: readonly TableOperation[] = ['SELECT', 'INSERT', 'UPDATE', 'DELETE'];

const stripComments = (sql: string): string => sql.replace(/--[^\n]*/g, '');
const keysIn = (text: string): string[] =>
  [...new Set([...text.matchAll(/has_platform_permission\('([a-z_.]+)'/g)].map((m) => m[1]))].sort();

// The policies as the migrations leave them, in file order: name -> the keys named by its last `create policy`;
// a later `drop policy` removes it.
function policiesAfterMigrations(): Map<string, string[]> {
  const dir = join(ROOT, 'supabase', 'migrations');
  const policies = new Map<string, string[]>();
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) {
    const sql = stripComments(readFileSync(join(dir, file), 'utf8'));
    const events = [
      ...[...sql.matchAll(/create\s+policy\s+"?([a-z0-9_]+)"?\s+on\s+[^;]*;/gi)].map((m) => ({
        at: m.index,
        name: m[1],
        keys: keysIn(m[0]),
      })),
      ...[...sql.matchAll(/drop\s+policy\s+(?:if\s+exists\s+)?"?([a-z0-9_]+)"?\s+on/gi)].map((m) => ({
        at: m.index,
        name: m[1],
        keys: null,
      })),
    ].sort((a, b) => a.at - b.at);
    for (const e of events) {
      if (e.keys) policies.set(e.name, e.keys);
      else policies.delete(e.name);
    }
  }
  return policies;
}

// The keys the generated pgTAP files admit per table and operation, from their "holder of <key> <OP> allowed" cases.
function generatedTestKeys(): Map<string, Set<string>> {
  const dir = join(ROOT, 'supabase', 'tests', 'database');
  const found = new Map<string, Set<string>>();
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql'))) {
    const sql = readFileSync(join(dir, file), 'utf8');
    if (!sql.includes('-- GENERATED by scripts/gen-staff-table-rls.ts')) continue;
    for (const m of sql.matchAll(/'([a-z0-9_]+): holder of ([a-z_.]+) (SELECT|INSERT|UPDATE|DELETE) allowed'/g)) {
      const id = `${m[1]} ${m[3]}`;
      if (!found.has(id)) found.set(id, new Set());
      found.get(id)!.add(m[2]);
    }
  }
  return found;
}

const POLICIES = policiesAfterMigrations();
const TEST_KEYS = generatedTestKeys();
const STAGED = (Object.keys(STAFF_TABLE_PERMISSIONS) as StaffTable[]).filter(
  (table) =>
    STAFF_TABLE_PERMISSIONS[table].group === 'permission' && OPS.some((op) => POLICIES.has(policyName(table, op))),
);

describe('the key each table policy names equals the map (design D10)', () => {
  it('covers the tables whose stage has landed, packages included', () => {
    expect(STAGED).toContain('packages');
  });

  for (const table of STAGED) {
    it(`${table}: the migrations' policy for each operation names the map's keys`, () => {
      for (const op of OPS) {
        const expected = [...staffTableOperationKeys(table, op)].sort();
        const actual = POLICIES.get(policyName(table, op)) ?? [];
        expect(actual, `${table} ${op}: the policy names [${actual}], the map says [${expected}]`).toEqual(expected);
      }
    });

    it(`${table}: the generated pgTAP cases admit the map's keys for each operation`, () => {
      for (const op of OPS) {
        const expected = [...staffTableOperationKeys(table, op)].sort();
        const actual = [...(TEST_KEYS.get(`${table} ${op}`) ?? [])].sort();
        expect(actual, `${table} ${op}: the pgTAP holders are [${actual}], the map says [${expected}]`).toEqual(expected);
      }
    });
  }
});

// Requirement "The model is provable and repeatable on a local database": every pgTAP file runs in one transaction that
// it rolls back (no side effects whether it passes, fails or aborts) and installs nothing from the network.
describe('the pgTAP suite is hermetic', () => {
  const dir = join(ROOT, 'supabase', 'tests', 'database');
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql'));

  it('has the files of every stage', () => {
    expect(files.length).toBeGreaterThanOrEqual(12);
  });

  for (const file of files) {
    it(`${file}: begins, rolls back, never commits, fetches nothing`, () => {
      const code = stripComments(readFileSync(join(dir, file), 'utf8'))
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean);
      expect(code[0]?.toLowerCase(), `${file}: first statement`).toBe('begin;');
      expect(code.at(-1)?.toLowerCase(), `${file}: last statement`).toBe('rollback;');
      const body = code.join('\n').toLowerCase();
      // A statement that is itself COMMIT or END (`on commit drop` on a temp table is not one).
      expect(body, `${file}: commit`).not.toMatch(/^(commit|end)(\s+(work|transaction))?\s*;/m);
      expect(body, `${file}: network or package installer`).not.toMatch(/dbdev|pg_tle|http_get|https?:\/\/|\bcopy\b.*\bprogram\b/);
    });
  }
});

// Requirement "The documented permission model is accurate" (task 7.2): the notes in dal.ts name the closed tables
// and the per-permission policies, and no longer say that no policy uses a fine-grained permission.
describe('dal.ts describes the model as it is', () => {
  const dal = readFileSync(join(ROOT, 'src', 'lib', 'auth', 'dal.ts'), 'utf8');

  it('does not claim that permissions appear in no policy', () => {
    expect(dal).not.toMatch(/zero policies/i);
  });

  it('names the floor, the closed tables, the per-permission policies and where the proof lives', () => {
    for (const heading of ['THE FLOOR', 'CLOSED TABLES', 'PER-PERMISSION POLICIES', 'WHERE THE PROOF LIVES']) {
      expect(dal, heading).toContain(heading);
    }
  });
});
